#!/usr/bin/env python3
"""
Build the Windows release executables for Safe File Sorter.
==========================================================

    python build_exe.py                 # build into dist/ (uses .build-venv if present)
    python build_exe.py --clean         # remove build/, dist/ and the venv first
    python build_exe.py --onedir        # folder build (starts faster) instead of one-file
    python build_exe.py --no-cli        # only the GUI executable
    python build_exe.py --install-tools # create .build-venv and install PyInstaller

What it does:

1. writes ``packaging/version_info.txt`` (the Windows version resource) from
   ``filesorter/version.py`` - the single source of truth for the version;
2. generates ``packaging/app.ico`` if it is missing (standard library only);
3. runs PyInstaller with ``packaging/safe_file_sorter.spec``.

Result, in ``dist/``:

* ``SafeFileSorter.exe``     - GUI, no console window  (this is the release file)
* ``SafeFileSorter-CLI.exe`` - console build for scripts and scheduled tasks

The executables are self-contained: no Python installation is needed on the
target machine.
"""

from __future__ import annotations

import argparse
import datetime as _dt
import os
import shutil
import subprocess
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent
PACKAGING = PROJECT / "packaging"
VENV = PROJECT / ".build-venv"
SPEC = PACKAGING / "safe_file_sorter.spec"
ICON = PACKAGING / "app.ico"
VERSION_INFO = PACKAGING / "version_info.txt"
DIST = PROJECT / "dist"
BUILD = PROJECT / "build"


def echo(message: str = "") -> None:
    try:
        print(message, flush=True)
    except UnicodeEncodeError:  # legacy console code page
        print(message.encode("ascii", "replace").decode("ascii"), flush=True)


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------
def python_in_venv() -> Path | None:
    for candidate in (VENV / "Scripts" / "python.exe", VENV / "bin" / "python"):
        if candidate.is_file():
            return candidate
    return None


def interpreter(with_tools: bool) -> Path:
    """Prefer the build venv; fall back to the current interpreter."""
    venv_python = python_in_venv()
    if venv_python is not None:
        return venv_python
    if with_tools:
        echo(f"Creating build environment in {VENV} ...")
        subprocess.run([sys.executable, "-m", "venv", str(VENV)], check=True)
        venv_python = python_in_venv()
        if venv_python is None:  # pragma: no cover - broken venv module
            raise SystemExit("Could not create a virtual environment.")
        echo("Installing PyInstaller (this needs internet access, once) ...")
        subprocess.run(
            [str(venv_python), "-m", "pip", "install", "--upgrade", "pip", "--quiet"],
            check=False,
        )
        subprocess.run(
            [str(venv_python), "-m", "pip", "install", "pyinstaller", "--quiet"],
            check=True,
        )
        return venv_python
    return Path(sys.executable)


def check_tools(python: Path) -> None:
    probe = subprocess.run(
        [str(python), "-c", "import PyInstaller; print(PyInstaller.__version__)"],
        capture_output=True,
        text=True,
        timeout=120,
    )
    if probe.returncode != 0:
        echo("PyInstaller is not available for:")
        echo(f"  {python}")
        echo()
        echo("Install it into a project-local environment and retry:")
        echo("  python build_exe.py --install-tools")
        echo("or:")
        echo("  python -m pip install pyinstaller")
        raise SystemExit(2)
    echo(f"PyInstaller {probe.stdout.strip()}")


def write_version_resource() -> None:
    """Generate the Windows version resource from filesorter/version.py."""
    sys.path.insert(0, str(PROJECT))
    from filesorter import version  # noqa: PLC0415

    numbers = tuple(version.FILE_VERSION) + (0,) * (4 - len(version.FILE_VERSION))
    # FixedFileInfo wants exactly four integers; the human readable form lives
    # in the StringFileInfo block below.
    file_version = ", ".join(str(part) for part in numbers[:4])
    description = f"{version.APP_NAME} - {version.DISPLAY_VERSION}"
    VERSION_INFO.write_text(
        f"""# UTF-8
# Generated by build_exe.py - do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({file_version}),
    prodvers=({file_version}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [StringStruct('CompanyName', '{version.COMPANY_NAME}'),
           StringStruct('FileDescription', '{description}'),
           StringStruct('FileVersion', '{version.APP_VERSION}'),
           StringStruct('InternalName', '{version.APP_NAME.replace(" ", "")}'),
           StringStruct('LegalCopyright', '{version.COPYRIGHT}'),
           StringStruct('OriginalFilename', 'SafeFileSorter.exe'),
           StringStruct('ProductName', '{version.APP_NAME}'),
           StringStruct('ProductVersion', '{version.APP_VERSION}')])
      ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
""",
        encoding="utf-8",
    )
    echo(f"Version resource: {VERSION_INFO.relative_to(PROJECT)}  ({description})")


def build(python: Path, one_dir: bool, no_cli: bool) -> int:
    # A separate work directory per layout keeps PyInstaller's cache honest when
    # switching between one-file and folder builds.
    work = BUILD / ("onedir" if one_dir else "onefile")
    arguments = [
        str(python),
        "-m",
        "PyInstaller",
        str(SPEC),
        "--noconfirm",
        "--distpath",
        str(DIST),
        "--workpath",
        str(work),
    ]
    echo()
    echo("Running PyInstaller (this takes a minute) ...")
    if one_dir:
        echo("layout: folder build (--onedir) - ship the whole dist folder")
    else:
        echo("layout: one-file build - a single portable .exe per variant")
    environment = dict(os.environ)
    environment["SAFE_FILE_SORTER_ONEDIR"] = "1" if one_dir else "0"
    environment["SAFE_FILE_SORTER_NO_CLI"] = "1" if no_cli else "0"
    return subprocess.run(arguments, env=environment, cwd=str(PROJECT)).returncode


def report(no_cli: bool, one_dir: bool) -> int:
    echo()
    echo("=" * 68)
    echo("Release artefacts")
    echo("=" * 68)
    expected = ["SafeFileSorter"]
    if not no_cli:
        expected.append("SafeFileSorter-CLI")
    missing = []
    for name in expected:
        suffix = "" if one_dir else ".exe"
        target = DIST / f"{name}{suffix}"
        if one_dir:
            target = DIST / name / f"{name}.exe"
            payload = DIST / name
        else:
            payload = target
        if payload.exists():
            size = target.stat().st_size if target.is_file() else 0
            echo(f"  {name + '.exe':<24} {size / 1024 / 1024:6.1f} MB   {target}")
        else:
            missing.append(str(target))
    if one_dir:
        echo()
        echo("  (built as a folder: ship the whole directory)")
    if missing:
        echo()
        echo("Missing:")
        for item in missing:
            echo(f"  {item}")
        return 1
    echo()
    echo("Done. SafeFileSorter.exe needs no Python installation - copy it anywhere")
    echo("and run it. The CLI variant accepts: SafeFileSorter-CLI.exe --cli --help")
    return 0


def clean(also_venv: bool) -> None:
    for folder in (BUILD, DIST):
        if folder.exists():
            echo(f"Removing {folder.relative_to(PROJECT)}/")
            shutil.rmtree(folder, ignore_errors=True)
    for cache in PROJECT.rglob("__pycache__"):
        shutil.rmtree(cache, ignore_errors=True)
    if also_venv and VENV.exists():
        echo(f"Removing {VENV.relative_to(PROJECT)}/")
        shutil.rmtree(VENV, ignore_errors=True)


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the Windows release executables.")
    parser.add_argument("--clean", action="store_true", help="remove build/ and dist/ first")
    parser.add_argument("--clean-all", action="store_true", help="also remove the build venv")
    parser.add_argument("--install-tools", action="store_true", help="create .build-venv and install PyInstaller")
    parser.add_argument("--onedir", action="store_true", help="folder build instead of one file")
    parser.add_argument("--no-cli", action="store_true", help="build only the GUI executable")
    args = parser.parse_args()

    echo(f"{'=' * 68}")
    echo("Safe File Sorter - release build")
    echo(f"{'=' * 68}")

    if args.clean_all:
        clean(also_venv=True)
    elif args.clean:
        clean(also_venv=False)

    if not ICON.exists():
        echo("Generating the application icon ...")
        subprocess.run([sys.executable, str(PACKAGING / "make_icon.py")], check=True)

    write_version_resource()

    python = interpreter(with_tools=args.install_tools)
    echo(f"Using interpreter: {python}")
    check_tools(python)

    code = build(python, one_dir=args.onedir, no_cli=args.no_cli)
    if code != 0:
        echo(f"PyInstaller failed with exit code {code}.")
        return code
    return report(args.no_cli, args.onedir)


if __name__ == "__main__":
    raise SystemExit(main())
